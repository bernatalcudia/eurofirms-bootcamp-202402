const { test, expect } = require('@playwright/test')

const api = 'http://127.0.0.1:19010'
const image = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/l2kAAAAASUVORK5CYII=', 'base64')
const password = 'test-password-123'

test('products and profile photo work through the app and API', async ({ page, request }) => {
  const username = 'browser-test-user'
  const register = await request.post(`${api}/users/register`, {
    data: { name: 'Browser User', username, password, email: 'browser@example.test', birthdate: '1990-01-01' },
  })
  expect(register.status()).toBe(201)
  const login = await request.post(`${api}/users/authenticate`, { data: { username, password } })
  expect(login.status()).toBe(200)
  const token = await login.json()
  const sellerRegister = await request.post(`${api}/users/register`, {
    data: { name: 'Test Seller', username: 'test-seller', password, email: 'seller@example.test', birthdate: '1990-01-01' },
  })
  expect(sellerRegister.status()).toBe(201)
  const sellerLogin = await request.post(`${api}/users/authenticate`, { data: { username: 'test-seller', password } })
  expect(sellerLogin.status()).toBe(200)
  const sellerToken = await sellerLogin.json()
  const photoUpdate = await request.patch(`${api}/users/me/profile`, {
    headers: { Authorization: `Bearer ${sellerToken}` },
    data: { photo: `data:image/png;base64,${image.toString('base64')}` },
  })
  expect(photoUpdate.status()).toBe(200)
  for (const [title, ownerToken] of [['Test Vase', token], ['Test Scarf', sellerToken]]) {
    const response = await request.post(`${api}/products/create`, {
      headers: { Authorization: `Bearer ${ownerToken}` },
      data: { images: [image.toString('base64')], title, brand: 'Test brand', description: 'Test description', price: 10, stock: 2, state: 'new' },
    })
    expect(response.status()).toBe(201)
  }

  await page.goto('/')
  await page.getByLabel('Username', { exact: true }).fill(username)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Log in' }).click()
  await expect(page.getByText('Test Vase').first()).toBeVisible()
  await expect(page.getByText('Test Scarf').first()).toBeVisible()
  const vaseCard = await page.getByRole('button', { name: 'View details for product Test Vase' }).first().boundingBox()
  const scarfCard = await page.getByRole('button', { name: 'View details for product Test Scarf' }).first().boundingBox()
  expect(vaseCard.height).toBeLessThanOrEqual(180)
  expect(scarfCard.height).toBeLessThanOrEqual(180)
  expect(Math.abs(vaseCard.y - scarfCard.y)).toBeLessThan(5)
  expect(Math.abs(vaseCard.x - scarfCard.x)).toBeGreaterThan(200)
  await page.setViewportSize({ width: 375, height: 812 })
  await expect.poll(async () => (await page.getByRole('button', { name: 'View details for product Test Vase' }).first().boundingBox()).height).toBeLessThanOrEqual(180)
  const mobileVase = await page.getByRole('button', { name: 'View details for product Test Vase' }).first().boundingBox()
  const mobileScarf = await page.getByRole('button', { name: 'View details for product Test Scarf' }).first().boundingBox()
  expect(Math.abs(mobileVase.x - mobileScarf.x)).toBeLessThan(5)
  expect(Math.abs(mobileVase.y - mobileScarf.y)).toBeGreaterThan(180)
  await page.setViewportSize({ width: 1200, height: 900 })

  await page.getByRole('button', { name: 'View details for product Test Scarf' }).first().click()
  await page.getByRole('button', { name: 'View seller profile' }).click()
  await expect(page.getByText('Test Seller')).toBeVisible()
  await expect(page.getByLabel('Profile photo').first()).toBeVisible()
  await page.getByRole('button', { name: /back/ }).click()
  await page.getByRole('button', { name: 'Message seller' }).click()
  await expect(page.getByText('test-seller').first()).toBeVisible()
  await page.getByRole('button', { name: /back/ }).click()
  await page.getByRole('button', { name: /back/ }).click()

  await page.getByLabel('Search products', { exact: true }).fill('Vase')
  await expect(page.getByText('Test Vase').first()).toBeVisible()
  await expect(page.getByText('Test Scarf').first()).toHaveCount(0)
  await page.getByRole('button', { name: /Like Test Vase/ }).click()
  await expect(page.getByRole('button', { name: /Unlike Test Vase/ })).toBeVisible()
  await expect(page.getByText('Test Scarf').first()).toHaveCount(0)
  await page.getByRole('button', { name: /Unlike Test Vase/ }).click()
  await expect(page.getByRole('button', { name: /Like Test Vase/ })).toBeVisible()
  await page.getByRole('button', { name: /View comments for product Test Vase/ }).click()
  await page.getByLabel('Comment input field').fill('Nice vase')
  await page.getByLabel('Send comment').click()
  await expect(page.getByText('Nice vase')).toBeVisible()
  await page.getByRole('button', { name: 'Edit comment' }).click()
  await page.getByLabel('Edit comment text').fill('Very nice vase')
  await page.getByRole('button', { name: 'Save modified comment' }).click()
  await expect(page.getByText('Very nice vase')).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Delete comment' }).click()
  await expect(page.getByText('Very nice vase')).toHaveCount(0)
  await page.getByRole('button', { name: 'Close comments' }).last().click()
  await page.getByRole('button', { name: 'Save Test Vase' }).click()
  await expect(page.getByRole('button', { name: 'Unsave Test Vase' })).toBeVisible()
  await page.getByRole('button', { name: 'Unsave Test Vase' }).click()
  await expect(page.getByRole('button', { name: 'Save Test Vase' })).toBeVisible()
  await page.getByRole('button', { name: 'Save Test Vase' }).click()
  await expect(page.getByRole('button', { name: 'Unsave Test Vase' })).toBeVisible()
  await page.getByRole('link', { name: 'Saved products tab' }).click()
  await page.getByRole('button', { name: 'View details for product Test Vase' }).click()
  await expect(page.getByLabel('Product name: Test Vase')).toBeVisible()
  const box = await page.getByLabel('Product image 1 of 1: Test Vase').boundingBox()
  expect(box.width).toBeLessThanOrEqual(460)
  expect(box.height).toBeLessThanOrEqual(320)
  await page.setViewportSize({ width: 375, height: 812 })
  await expect.poll(async () => (await page.getByLabel('Product image 1 of 1: Test Vase').boundingBox()).width).toBeLessThanOrEqual(311)
  await page.setViewportSize({ width: 1200, height: 900 })
  await page.getByRole('button', { name: 'Edit product' }).click()
  await page.getByPlaceholder('Enter product title').fill('Edited Vase')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByLabel('Product name: Edited Vase')).toBeVisible()
  await page.getByRole('button', { name: 'Delete product' }).first().click()
  await page.getByRole('button', { name: 'Cancel' }).click()
  await expect(page.getByLabel('Product name: Edited Vase')).toBeVisible()
  await page.getByRole('button', { name: 'Delete product' }).first().click()
  await page.getByRole('button', { name: 'Delete product' }).last().click()
  await expect(page.getByText('Edited Vase')).toHaveCount(0)

  await page.getByRole('link', { name: 'Create product tab' }).click()
  const chooserPromise = page.waitForEvent('filechooser')
  await page.getByLabel('Upload photos').click()
  const chooser = await chooserPromise
  await chooser.setFiles({ name: 'product.png', mimeType: 'image/png', buffer: image })
  await expect(page.getByLabel('Product image 1', { exact: true })).toBeVisible()
  await page.getByLabel('Product title', { exact: true }).fill('Test New Product')
  await page.getByLabel('Product brand', { exact: true }).fill('Test brand')
  await page.getByLabel('Product price', { exact: true }).fill('12')
  await page.getByLabel('Product stock', { exact: true }).fill('1')
  await page.getByLabel('Product description', { exact: true }).fill('A test listing')
  await page.getByLabel('Publish product').click()
  await page.getByRole('button', { name: 'Clear search' }).click()
  await expect(page.getByText('Test New Product').first()).toBeVisible()
  await expect(page.getByText('Test Scarf').first()).toBeVisible()

  await page.getByRole('link', { name: 'Profile and account settings tab' }).click()
  const photoChooserPromise = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: 'Choose profile photo' }).click()
  const photoChooser = await photoChooserPromise
  await photoChooser.setFiles({ name: 'profile.png', mimeType: 'image/png', buffer: image })
  await expect(page.getByLabel('Profile photo').first()).toBeVisible()
  await page.getByRole('button', { name: 'Save profile' }).click()
  const userId = JSON.parse(Buffer.from(token.split('.')[1], 'base64url').toString()).sub
  const getProfile = () => request.get(`${api}/users/${userId}`, { headers: { Authorization: `Bearer ${token}` } })
  await expect.poll(async () => (await (await getProfile()).json()).photo).toMatch(/^data:image\/(jpeg|png);base64,/)
  await page.reload()
  await page.getByLabel('Username', { exact: true }).fill(username)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Log in' }).click()
  await page.getByRole('link', { name: 'Profile and account settings tab' }).click()
  await expect(page.getByLabel('Profile photo').first()).toBeVisible()
  await page.getByRole('button', { name: 'Remove photo' }).click()
  await page.getByRole('button', { name: 'Save profile' }).click()
  await expect.poll(async () => (await (await getProfile()).json()).photo).toBeNull()
})
