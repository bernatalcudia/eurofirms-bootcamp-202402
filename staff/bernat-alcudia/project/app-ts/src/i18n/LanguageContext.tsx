type TranslationKey = keyof typeof translations.en

interface LanguageContextValue {
    language: Language
    setLanguage: (language: Language) => Promise<void>
    t: (key: TranslationKey | string, values?: Record<string, string | number>) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

function getDeviceLanguage(): Language {
    try {
        return Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase().startsWith('es') ? 'es' : 'en'
    } catch {
        return 'en'
    }
}

export function LanguageProvider({ children }: React.PropsWithChildren) {
    const [language, setLanguageState] = useState<Language>(getDeviceLanguage)

    useEffect(() => {
        AsyncStorage.getItem(languageStorageKey)
            .then(value => {
                if (value === 'en' || value === 'es') setLanguageState(value)
            })
            .catch(error => console.error('Could not load the saved language preference:', error))
    }, [])

    const setLanguage = useCallback(async (nextLanguage: Language) => {
        setLanguageState(nextLanguage)
        await AsyncStorage.setItem(languageStorageKey, nextLanguage)
    }, [])

    const t = useCallback<LanguageContextValue['t']>((key, values = {}) => {
        const dictionary = translations[language] as Record<string, string>
        const template = dictionary[key] ?? key
        return template.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
            Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder,
        )
    }, [language])

    const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t])

    return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
    const context = useContext(LanguageContext)
    if (!context) throw new Error('useLanguage must be used within a LanguageProvider')
    return context
}
